/**
 * admin.js - Personal `useritem` code generator (admin back-office).
 *
 * Reference: `.docs/gamemaster/useritemcode.md` and `js/business/UserItemCode.js` (the binary
 * format, the HMAC and the test vectors are authoritative; the generator reuses them verbatim so
 * the admin page and the game can never drift apart).
 *
 * ACCESS
 *   The page is gated by a password. Only the SHA-256 DIGEST of the password is stored here, never
 *   the password itself: the typed value is hashed in the browser and compared to `PASSWORD_HASH`.
 *   This is a UI barrier, NOT a security boundary: the page is a static file and the shared
 *   `useritemCode.key` is already public (it ships in `settings/config.json`), so anyone reading
 *   the sources can forge codes without ever opening this page. Do not give it more weight than it
 *   has.
 *
 * GENERATION
 *   One code carries ONE item and ONE quantity, so each reward line produces its own code. The
 *   payload (version, nonce, item hash, quantity, uuid tag, MAC) is built by
 *   `UserItemCode.generate()`, which is the exact counterpart of the verification the game runs.
 *   The shared key is read from `settings/config.json` so the page follows a key rotation without
 *   any code change.
 *
 * The page lives in `admin/` and imports the game module with a relative specifier
 * (`../js/business/UserItemCode.js`), which resolves from the page URL.
 */

import userItemCode, {
  UserItemCode,
  canonicalBooster,
  canonicalCard,
  canonicalSparks,
} from '../js/business/UserItemCode.js';

/**
 * SHA-256 (hex) of the admin password. Only the digest is stored: the password never appears in
 * this file. Regenerate it with `sha256("your password")` if the password changes.
 */
const PASSWORD_HASH = '19768d6a62452099c450e0e7d1ba4be25597c2669dcab5fea88fe73ae74ca39e';

/** Configuration fetched by the page (relative to `admin/`). */
const CONFIG_PATH = '../settings/config.json';

/** Default directory of the booster JSONs, used when `config.json` omits `boosters.directory`. */
const DEFAULT_BOOSTER_DIRECTORY = 'data/boosters';

/** Placeholder key shipped in `config.json`: it must be replaced before any real distribution. */
const PLACEHOLDER_KEY = 'AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=';

/** Reward kinds offered by the editor. */
const REWARD_KINDS = Object.freeze({ SPARKS: 'sparks', BOOSTER: 'booster', CARD: 'card' });

/** Maximum quantity representable by the `useritem` format (uint16). */
const MAX_QUANTITY = 65535;

/** Version 4 UUID pattern, matching the identifiers generated by the game. */
const UUID_V4_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/** Tab separator between the `Index` and the `Layout` of a card option value. */
const CARD_SEPARATOR = '\t';

/** @type {{sets: Array<{setId: string, name: string, cards: Array<{index: string, layout: string, name: string|null}>}>}|null} */
let catalog = null;
/** @type {Uint8Array|null} */
let keyBytes = null;


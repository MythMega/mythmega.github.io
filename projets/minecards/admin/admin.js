/**
 * Builds a labelled field wrapper.
 *
 * @param {string} label - Visible label.
 * @param {HTMLElement} control - Control element.
 * @returns {HTMLElement} The field element.
 */
function buildField(label, control) {
  const field = document.createElement('label');
  field.className = 'field';
  const span = document.createElement('span');
  span.className = 'field__label';
  span.textContent = label;
  field.append(span, control);
  return field;
}

/**
 * Builds the `<select>` of the reward kinds.
 *
 * @param {string} value - Initially selected kind.
 * @returns {HTMLSelectElement} The select element.
 */
function buildKindSelect(value) {
  const select = document.createElement('select');
  select.className = 'field__select';
  select.dataset.role = 'kind';
  [
    { value: REWARD_KINDS.SPARKS, label: 'Sparks' },
    { value: REWARD_KINDS.BOOSTER, label: 'Booster' },
    { value: REWARD_KINDS.BUNDLE, label: 'Bundle de blocs' },
    { value: REWARD_KINDS.CARD, label: 'Carte' },
    { value: REWARD_KINDS.DAILY_REWARD, label: 'Récompense de connexion' },
    { value: REWARD_KINDS.SKIP_DAY, label: 'Skip 1 jour' },
    { value: REWARD_KINDS.RESOURCE, label: 'Ressource minière' },
  ].forEach(({ value: optionValue, label }) => {
    if (optionValue === REWARD_KINDS.RESOURCE && miningResources.length === 0) return;
    const option = document.createElement('option');
    option.value = optionValue;
    option.textContent = label;
    select.appendChild(option);
  });
  select.value = value;
  return select;
}

/**
 * Builds the `<select>` of the extensions (disabled when no extension is known).
 *
 * The promo groups are listed after the extensions, marked `promo`, so the operator sees at once
 * which families are not drawable.
 *
 * @returns {HTMLSelectElement} The select element.
 */
function buildSetSelect() {
  const select = document.createElement('select');
  select.className = 'field__select';
  select.dataset.role = 'set';
  (catalog ?? []).forEach((set) => {
    const option = document.createElement('option');
    option.value = set.setId;
    option.textContent = `${set.promo ? 'Promo · ' : ''}${set.name} (${set.setId})`;
    select.appendChild(option);
  });
  select.disabled = (catalog ?? []).length === 0;
  return select;
}

/**
 * Builds the `<select>` of the cards of one extension.
 *
 * The option value packs `Index` and `Layout` with a tab: both are needed to rebuild the canonical
 * item, and neither can contain a tab.
 *
 * @param {string} setId - Extension id.
 * @returns {HTMLSelectElement} The select element.
 */
function buildCardSelect(setId) {
  const select = document.createElement('select');
  select.className = 'field__select';
  select.dataset.role = 'card';
  const set = (catalog ?? []).find((candidate) => candidate.setId === setId) ?? null;
  (set?.cards ?? []).forEach((card) => {
    const option = document.createElement('option');
    option.value = `${card.index}${CARD_SEPARATOR}${card.layout}`;
    option.textContent = `${card.index} · ${card.layout}${card.name ? ` · ${card.name}` : ''}`;
    select.appendChild(option);
  });
  select.disabled = (set?.cards ?? []).length === 0;
  return select;
}

/**
 * Builds the `<select>` of the mining resources.
 *
 * @param {string|null} selected - Initially selected slug.
 * @returns {HTMLSelectElement} The select element.
 */
function buildResourceSelect(selected = null) {
  const select = document.createElement('select');
  select.className = 'field__select';
  select.dataset.role = 'resource';
  miningResources.forEach((resource) => {
    const option = document.createElement('option');
    option.value = resource.slug;
    option.textContent = `${resource.name} (${resource.slug})`;
    select.appendChild(option);
  });
  select.disabled = miningResources.length === 0;
  if (selected && miningResources.some((resource) => resource.slug === selected)) {
    select.value = selected;
  }
  return select;
}

/**
 * Builds the quantity input.
 *
 * @param {number} [value=1] - Initial value.
 * @param {string} [label='Quantité'] - Visible label.
 * @returns {HTMLInputElement} The input element.
 */
function buildQuantityInput(value = 1, label = 'Quantité') {
  const input = document.createElement('input');
  input.className = 'field__input';
  input.type = 'number';
  input.min = '1';
  input.max = String(MAX_QUANTITY);
  input.step = '1';
  input.value = String(value);
  input.dataset.role = 'quantity';
  input.setAttribute('aria-label', label);
  return input;
}

/**
 * Creates one reward row (kind select + its dynamic fields + a remove button).
 *
 * @param {string} [kind=REWARD_KINDS.SPARKS] - Initially selected kind.
 * @param {string|null} [resourceSlug=null] - Initially selected resource.
 * @returns {HTMLElement} The row element.
 */
function buildRewardRow(kind = REWARD_KINDS.SPARKS, resourceSlug = null) {
  const row = document.createElement('div');
  row.className = 'reward';

  const preview = document.createElement('div');
  preview.className = 'reward__preview';
  preview.dataset.role = 'preview';
  preview.setAttribute('aria-hidden', 'true');

  const kindSelect = buildKindSelect(kind);
  const fields = document.createElement('div');
  fields.className = 'reward__fields';

  const remove = document.createElement('button');
  remove.type = 'button';
  remove.className = 'reward__remove';
  remove.textContent = 'Retirer';
  remove.addEventListener('click', () => row.remove());

  /**
   * Shows what the selected reward looks like in the game.
   *
   * The page only knows the catalogue, so the preview is the EXACT asset the player receives: the
   * pack of the extension, or the illustration of the chosen printing. Sparks, the daily-reward
   * advance and the "skip one day" preset have no picture of their own: the slot stays empty.
   *
   * @returns {void}
   */
  const renderPreview = () => {
    preview.textContent = '';
    preview.removeAttribute('title');
    const selected = kindSelect.value;
    const wantsSet = selected === REWARD_KINDS.BOOSTER || selected === REWARD_KINDS.CARD;
    const set = wantsSet
      ? (catalog ?? []).find(
          (candidate) => candidate.setId === fields.querySelector('[data-role="set"]')?.value
        ) ?? null
      : null;

    let source = null;
    let caption = '';
    if (selected === REWARD_KINDS.BOOSTER) {
      source = resolveAdminAsset(set?.texture ?? DEFAULT_BOOSTER_TEXTURE);
      caption = set ? `${set.name} (${set.setId})` : '';
    } else if (selected === REWARD_KINDS.BUNDLE) {
      source = resolveAdminAsset('assets/img/bundle.png');
      caption = 'Bundle de blocs';
    } else if (selected === REWARD_KINDS.RESOURCE) {
      const slug = fields.querySelector('[data-role="resource"]')?.value ?? '';
      const resource = miningResources.find((entry) => entry.slug === slug) ?? null;
      source = resource?.texture ?? null;
      caption = resource ? `${resource.name} (${resource.slug})` : '';
    } else if (selected === REWARD_KINDS.CARD) {
      const [index, layout] = (fields.querySelector('[data-role="card"]')?.value ?? '').split(CARD_SEPARATOR);
      const card =
        (set?.cards ?? []).find(
          (candidate) => candidate.index === index && candidate.layout === layout
        ) ?? null;
      source = resolveAdminAsset(card?.path ?? null);
      caption = card ? `${card.index} · ${card.layout}` : '';
    }

    if (!source) {
      preview.dataset.empty = 'true';
      preview.textContent = 'Aperçu';
      return;
    }

    delete preview.dataset.empty;
    const image = document.createElement('img');
    image.alt = caption;
    image.loading = 'lazy';
    image.src = source;
    image.addEventListener('error', () => {
      image.remove();
      preview.dataset.empty = 'true';
      preview.textContent = 'Aperçu indisponible';
    });
    preview.append(image);
    if (caption) preview.title = caption;
  };

  /**
   * Rebuilds the fields for the selected kind.
   *
   * @returns {void}
   */
  const renderFields = () => {
    fields.textContent = '';
    const selected = kindSelect.value;

    if (selected === REWARD_KINDS.BOOSTER) {
      const setSelect = buildSetSelect();
      const quantity = buildQuantityInput(1, 'Nombre de boosters');
      const wrapper = document.createElement('div');
      wrapper.append(
        buildField('Extension', setSelect),
        buildField('Boosters', quantity)
      );
      setSelect.addEventListener('change', renderPreview);
      fields.appendChild(wrapper);
    } else if (selected === REWARD_KINDS.BUNDLE) {
      fields.appendChild(
        buildField('Bundles de blocs', buildQuantityInput(1, 'Nombre de bundles de blocs'))
      );
    } else if (selected === REWARD_KINDS.RESOURCE) {
      const resourceSelect = buildResourceSelect(resourceSlug);
      resourceSelect.addEventListener('change', renderPreview);
      const quantity = buildQuantityInput(1, 'Quantité de ressource');
      fields.appendChild(
        document.createDocumentFragment()
      );
      fields.append(buildField('Ressource', resourceSelect), buildField('Quantité', quantity));
    } else if (selected === REWARD_KINDS.CARD) {
      const setSelect = buildSetSelect();
      const cardSelect = buildCardSelect(setSelect.value);
      setSelect.addEventListener('change', () => {
        const next = buildCardSelect(setSelect.value);
        cardSelect.replaceWith(next);
        cardSelect.disabled = next.disabled;
        next.addEventListener('change', renderPreview);
        renderPreview();
      });
      cardSelect.addEventListener('change', renderPreview);
      const quantity = buildQuantityInput(1, 'Nombre de cartes');
      const wrapper = document.createElement('div');
      wrapper.append(
        buildField('Extension', setSelect),
        buildField('Carte', cardSelect),
        buildField('Cartes', quantity)
      );
      fields.appendChild(wrapper);
    } else if (selected === REWARD_KINDS.DAILY_REWARD) {
      fields.appendChild(
        buildField(
          'Jours à avancer',
          buildQuantityInput(1, 'Jours de récompense de connexion à avancer')
        )
      );
    } else if (selected === REWARD_KINDS.SKIP_DAY) {
      const hint = document.createElement('p');
      hint.className = 'hint';
      hint.textContent = 'Avance la série des récompenses de connexion d’un jour.';
      fields.appendChild(hint);
    } else {
      fields.appendChild(buildField('Sparks à créditer', buildQuantityInput(100, 'Montant en Sparks')));
    }

    renderPreview();
  };

  kindSelect.addEventListener('change', renderFields);
  renderFields();

  row.append(preview, buildField('Type', kindSelect), fields, remove);
  return row;
}


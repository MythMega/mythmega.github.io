/**
 * Builds a labelled field wrapper.
 *
 * @param {string} label - Visible label.
 * @param {HTMLElement} control - Control element.
 * @returns {HTMLElement} The field element.
 */
function buildField(label, control) {
  const field = document.createElement('label');
  field.className = 'field';
  const span = document.createElement('span');
  span.className = 'field__label';
  span.textContent = label;
  field.append(span, control);
  return field;
}

/**
 * Builds the `<select>` of the reward kinds.
 *
 * @param {string} value - Initially selected kind.
 * @returns {HTMLSelectElement} The select element.
 */
function buildKindSelect(value) {
  const select = document.createElement('select');
  select.className = 'field__select';
  select.dataset.role = 'kind';
  [
    { value: REWARD_KINDS.SPARKS, label: 'Sparks' },
    { value: REWARD_KINDS.BOOSTER, label: 'Booster' },
    { value: REWARD_KINDS.CARD, label: 'Carte' },
  ].forEach(({ value: optionValue, label }) => {
    const option = document.createElement('option');
    option.value = optionValue;
    option.textContent = label;
    select.appendChild(option);
  });
  select.value = value;
  return select;
}

/**
 * Builds the `<select>` of the extensions (disabled when no extension is known).
 *
 * @returns {HTMLSelectElement} The select element.
 */
function buildSetSelect() {
  const select = document.createElement('select');
  select.className = 'field__select';
  select.dataset.role = 'set';
  (catalog ?? []).forEach((set) => {
    const option = document.createElement('option');
    option.value = set.setId;
    option.textContent = `${set.name} (${set.setId})`;
    select.appendChild(option);
  });
  select.disabled = (catalog ?? []).length === 0;
  return select;
}

/**
 * Builds the `<select>` of the cards of one extension.
 *
 * The option value packs `Index` and `Layout` with a tab: both are needed to rebuild the canonical
 * item, and neither can contain a tab.
 *
 * @param {string} setId - Extension id.
 * @returns {HTMLSelectElement} The select element.
 */
function buildCardSelect(setId) {
  const select = document.createElement('select');
  select.className = 'field__select';
  select.dataset.role = 'card';
  const set = (catalog ?? []).find((candidate) => candidate.setId === setId) ?? null;
  (set?.cards ?? []).forEach((card) => {
    const option = document.createElement('option');
    option.value = `${card.index}${CARD_SEPARATOR}${card.layout}`;
    option.textContent = `${card.index} · ${card.layout}${card.name ? ` · ${card.name}` : ''}`;
    select.appendChild(option);
  });
  select.disabled = (set?.cards ?? []).length === 0;
  return select;
}

/**
 * Builds the quantity input.
 *
 * @param {number} [value=1] - Initial value.
 * @param {string} [label='Quantité'] - Visible label.
 * @returns {HTMLInputElement} The input element.
 */
function buildQuantityInput(value = 1, label = 'Quantité') {
  const input = document.createElement('input');
  input.className = 'field__input';
  input.type = 'number';
  input.min = '1';
  input.max = String(MAX_QUANTITY);
  input.step = '1';
  input.value = String(value);
  input.dataset.role = 'quantity';
  input.setAttribute('aria-label', label);
  return input;
}

/**
 * Creates one reward row (kind select + its dynamic fields + a remove button).
 *
 * @param {string} [kind=REWARD_KINDS.SPARKS] - Initially selected kind.
 * @returns {HTMLElement} The row element.
 */
function buildRewardRow(kind = REWARD_KINDS.SPARKS) {
  const row = document.createElement('div');
  row.className = 'reward';

  const kindSelect = buildKindSelect(kind);
  const fields = document.createElement('div');
  fields.className = 'reward__fields';

  const remove = document.createElement('button');
  remove.type = 'button';
  remove.className = 'reward__remove';
  remove.textContent = 'Retirer';
  remove.addEventListener('click', () => row.remove());

  /**
   * Rebuilds the fields for the selected kind.
   *
   * @returns {void}
   */
  const renderFields = () => {
    fields.textContent = '';
    const selected = kindSelect.value;

    if (selected === REWARD_KINDS.BOOSTER) {
      const setSelect = buildSetSelect();
      const quantity = buildQuantityInput(1, 'Nombre de boosters');
      const wrapper = document.createElement('div');
      wrapper.append(
        buildField('Extension', setSelect),
        buildField('Boosters', quantity)
      );
      fields.appendChild(wrapper);
      return;
    }

    if (selected === REWARD_KINDS.CARD) {
      const setSelect = buildSetSelect();
      const cardSelect = buildCardSelect(setSelect.value);
      setSelect.addEventListener('change', () => {
        const next = buildCardSelect(setSelect.value);
        cardSelect.replaceWith(next);
        cardSelect.disabled = next.disabled;
      });
      const quantity = buildQuantityInput(1, 'Nombre de cartes');
      const wrapper = document.createElement('div');
      wrapper.append(
        buildField('Extension', setSelect),
        buildField('Carte', cardSelect),
        buildField('Cartes', quantity)
      );
      fields.appendChild(wrapper);
      return;
    }

    fields.appendChild(buildField('Sparks à créditer', buildQuantityInput(100, 'Montant en Sparks')));
  };

  kindSelect.addEventListener('change', renderFields);
  renderFields();

  row.append(buildField('Type', kindSelect), fields, remove);
  return row;
}


/**
 * Locks the interface again (the data stays in memory; the gate is purely visual).
 *
 * @returns {void}
 */
function lockApp() {
  app.hidden = true;
  lock.hidden = false;
  lockInput.value = '';
  setFeedback(lockFeedback, null);
  lockInput.focus();
}

/**
 * Opens the generator: loads the configuration, the catalog and the key.
 *
 * @returns {Promise<void>} Resolves once the interface is ready.
 */
async function unlockApp() {
  lock.hidden = true;
  app.hidden = false;

  if (!globalThis.crypto?.subtle) {
    setFeedback(feedback, 'crypto.subtle est indisponible : servez la page en HTTPS ou sur localhost.', 'error');
    generate.disabled = true;
    return;
  }

  try {
    const config = await fetchConfig();
    const { keyBytes: key, status } = resolveKey(config);
    keyBytes = key;
    setFeedback(keyStatus, status.text, status.tone);
    catalog = await loadCatalog(config);
  } catch (error) {
    console.error('[Admin] Configuration load failed.', error);
    setFeedback(keyStatus, error.message, 'error');
    catalog = [];
    keyBytes = null;
  }

  if (!catalog || catalog.length === 0) {
    setFeedback(keyStatus, 'Aucune extension chargée : seuls les Sparks sont disponibles.', 'warning');
  }
  if (!keyBytes) {
    generate.disabled = true;
  }
}

lockForm.addEventListener('submit', async (event) => {
  event.preventDefault();
  const typed = lockInput.value;
  if (typed === '') {
    setFeedback(lockFeedback, 'Saisissez le mot de passe.', 'error');
    return;
  }
  try {
    const digest = await sha256Hex(typed);
    if (!constantTimeEqual(digest, PASSWORD_HASH)) {
      setFeedback(lockFeedback, 'Mot de passe incorrect.', 'error');
      lockInput.value = '';
      return;
    }
  } catch (error) {
    setFeedback(lockFeedback, error.message, 'error');
    return;
  }
  lockInput.value = '';
  await unlockApp();
});

lockAgain.addEventListener('click', () => lockApp());

addReward.addEventListener('click', () => {
  rewards.appendChild(buildRewardRow());
});

uuidInput.addEventListener('input', () => {
  const value = uuidInput.value.trim();
  uuidInput.dataset.valid = value === '' ? '' : String(isUuidV4(value));
});

generate.addEventListener('click', async () => {
  setFeedback(feedback, null);
  resultCardReset();

  const uuid = uuidInput.value.trim();
  if (!isUuidV4(uuid)) {
    setFeedback(feedback, 'UUID invalide : attendu un UUID v4 (celui du compte, visible dans ses Réglages).', 'error');
    return;
  }
  if (!keyBytes) {
    setFeedback(feedback, 'Clé partagée indisponible : impossible de générer un code vérifiable.', 'error');
    return;
  }

  const rows = [...rewards.querySelectorAll('.reward')];
  if (rows.length === 0) {
    setFeedback(feedback, 'Ajoutez au moins une récompense.', 'error');
    return;
  }

  const generated = [];
  try {
    for (const row of rows) {
      const reward = readReward(row);
      const result = await userItemCode.generate({
        // The shared singleton is used with an injected key: no configuration is ever fetched,
        // so the page never tries to read `settings/config.json` from the `admin/` path.
        uuid,
        canonical: reward.canonical,
        quantity: reward.quantity,
        key: keyBytes,
      });
      generated.push({ label: reward.label, code: result.code });
    }
  } catch (error) {
    console.error('[Admin] Generation failed.', error);
    setFeedback(feedback, error.message ?? 'La génération a échoué.', 'error');
    return;
  }

  resultsList.textContent = '';
  generated.forEach((entry) => resultsList.appendChild(buildResultItem(entry)));
  resultsCard.hidden = false;
  setFeedback(
    feedback,
    `${generated.length} code(s) généré(s) pour ${uuid}.`,
    'success'
  );
});

/**
 * Empties the results list and hides its card.
 *
 * @returns {void}
 */
function resultCardReset() {
  resultsList.textContent = '';
  resultsCard.hidden = true;
}


/**
 * Fetches `settings/config.json`.
 *
 * @returns {Promise<object>} The parsed configuration.
 * @throws {Error} When the request fails or the payload is not JSON.
 */
async function fetchConfig() {
  let response;
  try {
    response = await fetch(CONFIG_PATH, { cache: 'no-store' });
  } catch (error) {
    throw new Error('Impossible de lire settings/config.json (réseau).', { cause: error });
  }
  if (!response.ok) {
    throw new Error(`Impossible de lire settings/config.json (HTTP ${response.status}).`);
  }
  try {
    return await response.json();
  } catch (error) {
    throw new Error('settings/config.json n’est pas un JSON valide.', { cause: error });
  }
}

/**
 * Fetches `settings/cardsets.json`: the declared sets, their release date and their promo flag.
 *
 * The catalogue is the single source of the set list (it replaced `boosters.sets` of the
 * configuration): this page reads it so a set added to the game shows up here without a second
 * declaration. The release date is not used - a personal code may grant a card of an announced set
 * deliberately - only the order, the identifiers and the `promo` flag are.
 *
 * @returns {Promise<Array<{id: string, promo: boolean}>>} The declared sets, in file order.
 * @throws {Error} When the request fails or the payload is not JSON.
 */
async function fetchCardSets() {
  let response;
  try {
    response = await fetch('../settings/cardsets.json', { cache: 'no-store' });
  } catch (error) {
    throw new Error('Impossible de lire settings/cardsets.json (réseau).', { cause: error });
  }
  if (!response.ok) {
    throw new Error(`Impossible de lire settings/cardsets.json (HTTP ${response.status}).`);
  }
  let payload;
  try {
    payload = await response.json();
  } catch (error) {
    throw new Error('settings/cardsets.json n’est pas un JSON valide.', { cause: error });
  }

  return (Array.isArray(payload?.sets) ? payload.sets : [])
    .map((entry) => ({
      id: typeof entry?.id === 'string' ? entry.id.trim() : '',
      promo: entry?.promo === true,
    }))
    .filter((entry) => entry.id !== '');
}

/**
 * Reads the shared key from the configuration and validates it.
 *
 * @param {object} config - Parsed configuration.
 * @returns {{keyBytes: Uint8Array|null, status: {text: string, tone: string}}} The key and the
 *   status line to display to the operator.
 */
function resolveKey(config) {
  const raw = config?.useritemCode?.key;
  if (typeof raw !== 'string' || raw.trim() === '') {
    return {
      keyBytes: null,
      status: {
        text: 'Aucune clé « useritemCode.key » dans settings/config.json : les codes générés ne seront pas vérifiables.',
        tone: 'error',
      },
    };
  }
  let bytes;
  try {
    bytes = UserItemCode.base64ToBytes(raw.trim());
  } catch (error) {
    return {
      keyBytes: null,
      status: { text: 'La clé « useritemCode.key » n’est pas du base64 valide.', tone: 'error' },
    };
  }
  if (bytes.length !== 32) {
    return {
      keyBytes: null,
      status: {
        text: `La clé « useritemCode.key » fait ${bytes.length} octets au lieu de 32 : les codes ne seront pas vérifiables.`,
        tone: 'error',
      },
    };
  }
  if (raw.trim() === PLACEHOLDER_KEY) {
    return {
      keyBytes: bytes,
      status: {
        text: 'Attention : la clé par défaut (32 zéros) est encore en place. Remplacez-la dans settings/config.json avant de distribuer des codes.',
        tone: 'warning',
      },
    };
  }
  return { keyBytes: bytes, status: { text: 'Clé partagée chargée (32 octets).', tone: 'success' } };
}

/**
 * Reads one catalog file (relative to `admin/`) and returns its parsed payload.
 *
 * @param {string} directory - Directory holding the file, relative to the application root.
 * @param {string} fileName - File basename, without its extension.
 * @returns {Promise<object>} The parsed JSON.
 * @throws {Error} When the request fails or the payload is not JSON.
 */
async function fetchCatalogFile(directory, fileName) {
  const response = await fetch(`../${directory}/${fileName}.json`, { cache: 'no-store' });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  return response.json();
}

/**
 * Reads the card rows of a catalog payload, in the shape the reward editor needs.
 *
 * Both spellings of the list are accepted: `Cards`/`cards` in an extension file, `Card` in a promo
 * file. Only `Index` and `Layout` matter - they are what `canonicalCard()` is built from - so an
 * entry missing either one is dropped rather than offered as a reward that could never match.
 *
 * @param {object} raw - Parsed catalog payload.
 * @returns {Array<{index: string, layout: string, name: string|null, path: string|null}>} The card
 *   options, with the illustration the game displays.
 */
function collectCardRows(raw) {
  const entries = Array.isArray(raw?.Cards)
    ? raw.Cards
    : Array.isArray(raw?.cards)
      ? raw.cards
      : Array.isArray(raw?.Card)
        ? raw.Card
        : [];

  return entries
    .filter((entry) => entry && typeof entry.Index === 'string' && typeof entry.Layout === 'string')
    .map((entry) => ({
      index: entry.Index,
      layout: entry.Layout,
      name: typeof entry.Name_FR === 'string' ? entry.Name_FR : null,
      path: typeof entry.Path === 'string' && entry.Path.trim() !== '' ? entry.Path.trim() : null,
    }));
}

/**
 * Normalises a declared reward type into the slug used by the game.
 *
 * @param {unknown} type - `Type` of a reward in `settings/mining.json`.
 * @returns {string} The lowercase underscore slug.
 */
function resourceSlugOf(type) {
  return String(type ?? '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
}

/**
 * Resolves a catalogue path from the `admin/` page.
 *
 * The catalogues are written for the game root (`./assets/...`) and the illustrations point at the
 * asset CDN (`<lang>` is a placeholder of the card renderer). The preview therefore prefixes a
 * local path with `../` and pins the language to `en`, the default card language of the game.
 *
 * @param {string|null|undefined} value - Path read from a catalogue.
 * @returns {string|null} The URL usable by the page, or null when there is no path.
 */
function resolveAdminAsset(value) {
  if (typeof value !== 'string' || value.trim() === '') return null;
  const path = value.trim().replaceAll('<lang>', 'en');
  if (/^(?:[a-z][a-z0-9+.-]*:|\/\/)/i.test(path)) return path;
  return `../${path.replace(/^\.\//, '')}`;
}

/**
 * Loads the five resources of the mine, in declaration order.
 *
 * The slugs are derived exactly like `MiningManager.normalizeBlocks()` does, because that is the key
 * `user_state.mining.resources` and `canonicalMiningResource()` use. A failure only disables the
 * resource kind; the other rewards stay usable.
 *
 * @param {object} config - Parsed configuration.
 * @returns {Promise<Array<{slug: string, name: string, texture: string|null}>>} The resources.
 */
async function loadMiningResources(config) {
  const path = String(config?.mining?.configPath ?? 'settings/mining.json').replace(/^\.\//, '');
  const slash = path.lastIndexOf('/');
  const directory = slash >= 0 ? path.slice(0, slash) : '.';
  const fileName = path.slice(slash + 1).replace(/\.json$/i, '');
  const raw = await fetchCatalogFile(directory, fileName);
  const resources = [];
  (Array.isArray(raw?.Blocks) ? raw.Blocks : []).forEach((block) => {
    (Array.isArray(block?.Rewards) ? block.Rewards : []).forEach((reward) => {
      const slug = resourceSlugOf(reward?.Type);
      if (slug === '' || slug === 'sparks' || resources.some((entry) => entry.slug === slug)) return;
      resources.push({
        slug,
        name: String(reward?.Type ?? slug),
        texture: resolveAdminAsset(reward?.Texture ?? null),
      });
    });
  });
  return resources;
}

/**
 * Loads every declared extension AND every declared promo group (the same sources the game uses).
 *
 * The promo groups are part of the catalog on purpose: a personal code can grant a promo card
 * exactly like a drawn one (that is the only way such a card ever enters a collection), so the
 * operator must be able to pick one here. The sets and their promo flag come from
 * `settings/cardsets.json` (the declaration the game itself reads), and a series without a promo
 * file is simply skipped: a missing promo is the normal case, never an error.
 *
 * @param {object} config - Parsed configuration (directories only).
 * @returns {Promise<Array<{setId: string, name: string, promo: boolean, texture: string|null, cards: Array<{index: string, layout: string, name: string|null, path: string|null}>}>>}
 *   The catalog.
 * @throws {Error} When the catalogue cannot be read or a declared extension file is missing.
 */
async function loadCatalog(config) {
  const cardSets = await fetchCardSets();
  const sets = cardSets.map((entry) => entry.id);
  const directory =
    typeof config?.boosters?.directory === 'string' && config.boosters.directory.trim() !== ''
      ? config.boosters.directory.trim().replace(/^\.\//, '')
      : DEFAULT_BOOSTER_DIRECTORY;

  const result = [];
  for (const setId of sets) {
    let raw;
    try {
      raw = await fetchCatalogFile(directory, setId);
    } catch (error) {
      throw new Error(`Extension « ${setId} » illisible (${directory}/${setId}.json).`, { cause: error });
    }

    result.push({
      setId,
      name: typeof raw?.Name === 'string' && raw.Name !== '' ? raw.Name : setId,
      promo: false,
      texture: typeof raw?.BoosterTexture === 'string' && raw.BoosterTexture.trim() !== ''
        ? raw.BoosterTexture.trim()
        : null,
      cards: collectCardRows(raw),
    });
  }

  const promoDirectory =
    typeof config?.promos?.directory === 'string' && config.promos.directory.trim() !== ''
      ? config.promos.directory.trim().replace(/^\.\//, '')
      : DEFAULT_PROMO_DIRECTORY;
  // The `promo` flag of the catalogue is the only source, exactly like in the game
  // (`ConfigLoader.getPromoSettings()`).
  const promoSets = cardSets.filter((entry) => entry.promo).map((entry) => entry.id);

  for (const parentId of promoSets) {
    const setId = `${parentId}${PROMO_SET_SUFFIX}`;
    let raw;
    try {
      raw = await fetchCatalogFile(promoDirectory, parentId);
    } catch (error) {
      console.info(
        `[Admin] Pas de promo pour « ${parentId} » (${promoDirectory}/${parentId}.json), série ignorée.`
      );
      continue;
    }

    const cards = collectCardRows(raw);
    if (cards.length === 0) {
      console.warn(`[Admin] « ${promoDirectory}/${parentId}.json » ne déclare aucune carte promo : ignoré.`);
      continue;
    }

    // `Name` is the title of the series, `Serie` its short label (`data/promo_cards/*.json`).
    const declaredName = typeof raw?.Name === 'string' && raw.Name !== '' ? raw.Name : null;
    const declaredLabel = typeof raw?.Serie === 'string' && raw.Serie !== '' ? raw.Serie : null;
    result.push({
      setId,
      name: declaredName ?? declaredLabel ?? setId,
      promo: true,
      // A promo group is never a drawable pack: there is no pack art to preview.
      texture: null,
      cards,
    });
  }

  return result;
}


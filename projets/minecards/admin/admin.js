/**
 * Reads one reward row into `{ canonical, quantity, label }`.
 *
 * @param {HTMLElement} row - Reward row.
 * @returns {{canonical: string, quantity: number, label: string}} The parsed reward.
 * @throws {Error} When the row is incomplete.
 */
function readReward(row) {
  const kind = row.querySelector('[data-role="kind"]')?.value;
  const quantity = Number(row.querySelector('[data-role="quantity"]')?.value);
  if (!Number.isInteger(quantity) || quantity < 1 || quantity > MAX_QUANTITY) {
    throw new Error(`Quantité invalide (entier entre 1 et ${MAX_QUANTITY}).`);
  }

  if (kind === REWARD_KINDS.SPARKS) {
    return { canonical: canonicalSparks(), quantity, label: `${quantity} Sparks` };
  }

  const setId = row.querySelector('[data-role="set"]')?.value ?? '';
  if (!setId) throw new Error('Sélectionnez une extension.');

  if (kind === REWARD_KINDS.BOOSTER) {
    return {
      canonical: canonicalBooster(setId),
      quantity,
      label: `${quantity} × booster ${setId}`,
    };
  }

  const raw = row.querySelector('[data-role="card"]')?.value ?? '';
  const [index, layout] = raw.split(CARD_SEPARATOR);
  if (!index || !layout) throw new Error('Sélectionnez une carte.');
  return {
    canonical: canonicalCard(index, layout),
    quantity,
    label: `${quantity} × carte ${index} (${layout})`,
  };
}

/**
 * Builds one result list item (label, code and a copy button).
 *
 * @param {{label: string, code: string}} payload - Generated code.
 * @returns {HTMLLIElement} The list item.
 */
function buildResultItem({ label, code }) {
  const item = document.createElement('li');
  item.className = 'result';

  const caption = document.createElement('span');
  caption.className = 'result__label';
  caption.textContent = label;

  const rowElement = document.createElement('div');
  rowElement.className = 'result__row';

  const codeElement = document.createElement('code');
  codeElement.className = 'result__code';
  codeElement.textContent = code;

  const copy = document.createElement('button');
  copy.type = 'button';
  copy.className = 'btn btn--ghost';
  copy.textContent = 'Copier';
  copy.addEventListener('click', () => {
    copyText(code)
      .then(() => {
        copy.textContent = 'Copié';
        window.setTimeout(() => {
          copy.textContent = 'Copier';
        }, 1500);
      })
      .catch((error) => {
        console.error('[Admin] Copy failed.', error);
      });
  });

  rowElement.append(codeElement, copy);
  item.append(caption, rowElement);
  return item;
}


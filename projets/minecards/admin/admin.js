/**
 * Writes a message into a feedback paragraph.
 *
 * @param {HTMLElement|null} element - Target paragraph.
 * @param {string|null} text - Message, or null to hide the paragraph.
 * @param {'info'|'success'|'warning'|'error'} [tone='info'] - Visual tone.
 * @returns {void}
 */
function setFeedback(element, text, tone = 'info') {
  if (!element) return;
  if (!text) {
    element.hidden = true;
    element.textContent = '';
    element.removeAttribute('data-tone');
    return;
  }
  element.hidden = false;
  element.textContent = text;
  element.dataset.tone = tone;
}

/**
 * Computes the SHA-256 hex digest of a text.
 *
 * @param {string} text - Text to hash.
 * @returns {Promise<string>} Lowercase hex digest.
 * @throws {Error} When `crypto.subtle` is unavailable (insecure context).
 */
async function sha256Hex(text) {
  if (!globalThis.crypto?.subtle) {
    throw new Error('crypto.subtle est indisponible : servez la page en HTTPS ou sur localhost.');
  }
  const digest = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(text));
  return [...new Uint8Array(digest)].map((byte) => byte.toString(16).padStart(2, '0')).join('');
}

/**
 * Compares two strings without an early exit (avoids leaking the matching prefix length).
 *
 * @param {string} left - First string.
 * @param {string} right - Second string.
 * @returns {boolean} True when both are identical.
 */
function constantTimeEqual(left, right) {
  if (left.length !== right.length) return false;
  let difference = 0;
  for (let index = 0; index < left.length; index += 1) {
    difference |= left.charCodeAt(index) ^ right.charCodeAt(index);
  }
  return difference === 0;
}

/**
 * Checks whether a value is a version 4 UUID.
 *
 * @param {unknown} value - Candidate identifier.
 * @returns {boolean} True for a v4 UUID.
 */
function isUuidV4(value) {
  return typeof value === 'string' && UUID_V4_PATTERN.test(value.trim());
}

/**
 * Copies a text to the clipboard, with a fallback for non-secure contexts.
 *
 * @param {string} text - Text to copy.
 * @returns {Promise<void>} Resolves once the copy was attempted.
 * @throws {Error} When both strategies fail.
 */
async function copyText(text) {
  if (navigator.clipboard && typeof navigator.clipboard.writeText === 'function') {
    await navigator.clipboard.writeText(text);
    return;
  }
  const area = document.createElement('textarea');
  area.value = text;
  area.setAttribute('readonly', '');
  area.style.position = 'fixed';
  area.style.opacity = '0';
  document.body.appendChild(area);
  area.select();
  const ok = document.execCommand('copy');
  area.remove();
  if (!ok) throw new Error('La copie dans le presse-papier a échoué.');
}

